@pytest.fixture
def temp_dir():
    d = tempfile.mkdtemp(prefix="resilight_test_")
    yield d
    shutil.rmtree(d, ignore_errors=True)


def test_sumo_binary_resolution():
    """Verify that SUMO home and essential binaries can be located."""
    home = get_sumo_home()
    assert os.path.isdir(home), f"SUMO_HOME does not exist: {home}"

    bin_dir = get_sumo_bin_dir()
    assert os.path.isdir(bin_dir), f"bin dir does not exist: {bin_dir}"

    sumo_exe = get_binary("sumo")
    assert os.path.isfile(sumo_exe), f"sumo binary not found: {sumo_exe}"

    netconvert_exe = get_binary("netconvert")
    assert os.path.isfile(netconvert_exe), f"netconvert binary not found: {netconvert_exe}"


def test_4way_network_generation(temp_dir):
    """Verify netconvert builds a 4-way intersection with default traffic light phases."""
    net_file, tls_id = build_4way_network(temp_dir)
    assert os.path.isfile(net_file)
    assert tls_id == "J0"

    with open(net_file, "r", encoding="utf-8") as f:
        content = f.read()

    assert '<tlLogic id="J0"' in content
    # Verify default netconvert generates 4 phases (NS green, NS yellow, EW green, EW yellow)
    assert content.count("<phase duration=") >= 4


