def test_fixed_time_controller_logic():
    """Verify that FixedTimeController cycles through phases as expected."""
    custom_cycle = [(0, 10.0), (1, 2.0), (2, 8.0), (3, 2.0)]
    ctrl = FixedTimeController("J0", phase_cycle=custom_cycle)

    assert ctrl.current_phase == 0
    # Step 5 seconds -> still in phase 0
    for _ in range(5):
        p = ctrl.step(1.0)
    assert p == 0

    # Step another 5 seconds -> phase 0 expires (10s total), switches to phase 1
    for _ in range(5):
        p = ctrl.step(1.0)
    assert p == 1

    # Step 2 seconds -> phase 1 expires (2s), switches to phase 2
    for _ in range(2):
        p = ctrl.step(1.0)
    assert p == 2

    # Step 8 seconds -> phase 2 expires (8s), switches to phase 3
    for _ in range(8):
        p = ctrl.step(1.0)
    assert p == 3

    # Step 2 seconds -> phase 3 expires, wraps around to phase 0
    for _ in range(2):
        p = ctrl.step(1.0)
    assert p == 0


def test_traci_simulation_lifecycle(temp_dir):
    """Verify end-to-end SUMO TraCI execution and metrics recording."""
    net_file, tls_id = build_4way_network(temp_dir)
    rou_file = build_4way_demand(temp_dir, duration_s=100.0, main_vph=1000, side_vph=600)

    with SumoTraciWrapper(net_file, rou_file, step_length=1.0) as sim:
        assert sim.is_running
        assert tls_id in sim.get_tls_ids()

        for _ in range(25):
            sim.step()

        assert sim.get_time() == 25.0

        state = sim.get_intersection_state(tls_id)
        assert isinstance(state, IntersectionState)
        assert state.tls_id == tls_id
        assert state.total_vehicles > 0
        assert len(state.lane_queues) > 0

        # Change phase manually
        sim.set_phase(tls_id, 2)
        assert sim.get_phase(tls_id) == 2

        metrics = sim.get_metrics()
        assert isinstance(metrics, SimulationMetrics)
        assert metrics.step_count == 25
        assert metrics.active_vehicles > 0

    assert not sim.is_running


def test_fixed_time_driving_simulation(temp_dir):
    """Verify FixedTimeController driving SumoTraciWrapper over multiple cycles."""
    net_file, tls_id = build_4way_network(temp_dir)
    rou_file = build_4way_demand(temp_dir, duration_s=100.0, main_vph=800, side_vph=400)

    # 10s green, 2s yellow cycle for fast testing
    cycle = [(0, 10.0), (1, 2.0), (2, 10.0), (3, 2.0)]
    controller = FixedTimeController(tls_id, phase_cycle=cycle)

    phases_observed = []
    with SumoTraciWrapper(net_file, rou_file, step_length=1.0) as sim:
        for _ in range(40):
            target_phase = controller.step(1.0)
            sim.set_phase(tls_id, target_phase)
            sim.step()
            phases_observed.append(sim.get_phase(tls_id))

    # Should have observed multiple phases: 0, 1, 2, 3
    unique_phases = set(phases_observed)
    assert {0, 1, 2, 3}.issubset(unique_phases), f"Observed phases: {unique_phases}"
