"""
LLM Diagnostic Agent Module for ResiLight.

ARCHITECTURAL SAFETY BOUNDARY:
------------------------------
This Agent operates STRICTLY in the read-only Dashboard / Observability layer.
It reads historical degradation logs from the Cloud layer and generates human-readable
root-cause analysis and operational recommendations for traffic control center operators.
It has ZERO write access or control authority over the Edge RSU signal controllers.

CAPABILITIES:
-------------
1. Reads JSON audit logs generated by DegradationFSM (`sim_output/degradation_events.json`).
2. Extracts outage characteristics (duration, peak loss rate, queue impact).
3. Calls Gemini API (via GEMINI_API_KEY) or executes built-in Domain Expert Diagnostic Engine.
4. Outputs structured Traditional Chinese diagnostic reports and recommendations.
"""
import os
import json
import logging
import urllib.request
import urllib.error
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any

logger = logging.getLogger("llm_agent")


@dataclass
class DiagnosticReport:
    """Diagnostic synthesis generated by the LLM Agent."""
    incident_title: str
    severity: str                       # "CRITICAL", "WARNING", "INFO"
    incident_duration_s: float
    probable_cause: str
    impact_assessment: str
    operator_recommendations: List[str]
    raw_response: str
    llm_source: str                     # "Gemini-API" or "Domain-Expert-Fallback"


class LLMDiagnosticAgent:
    """
    Analyzes degradation event logs and generates actionable operator intelligence.
    """

    def __init__(self, api_key: Optional[str] = None, model_name: str = "gemini-2.5-flash"):
        self.api_key = api_key or os.environ.get("GEMINI_API_KEY")
        self.model_name = model_name

    def load_events(self, log_filepath: str) -> List[Dict[str, Any]]:
        """Loads degradation transition records from a JSON file."""
        if not os.path.exists(log_filepath):
            raise FileNotFoundError(f"Log file not found: {log_filepath}")
        with open(log_filepath, "r", encoding="utf-8") as f:
            return json.load(f)

    def generate_prompt(self, events: List[Dict[str, Any]]) -> str:
        """Constructs an analytical prompt in Traditional Chinese."""
        events_json_str = json.dumps(events, indent=2, ensure_ascii=False)
        prompt = f"""你是一名負責「中華電信 5G MEC 智慧號誌維運中心」的高級資安與通訊可靠度診斷專家。
以下是 ResiLight 智慧號誌系統在路口邊緣端記錄的網路通訊劣化與狀態機降階日誌：

```json
{events_json_str}
```

系統架構說明：
- Level 0 (NORMAL): 5G URLLC 連線正常，執行全局 MARL 協同控制。
- Level 1 (PARTIAL): 網路輕微劣化，降階至相鄰路口 P2P 局部協同。
- Level 2 (FALLBACK): 網路中斷或嚴重丟包，啟用純本地 Max Pressure 規則引擎獨立防護。

請依據上述日誌進行深度專業診斷，並以繁體中文給出以下四個結構化分析：
1. 【事件綜整與成因推論】：說明通訊中斷的時長、特徵（例如是暫時性電波干擾、基站高負載排擠，還是施工挖斷光纖之實體中斷）。
2. 【交通衝擊評估】：分析降階期間 Max Pressure 是否有效防止路口癱瘓，以及恢復過程是否平穩。
3. 【交控中心處置建議】：列出 3 點具體可行的交控/通訊維護操作建議。
4. 【嚴重度等級】：評定為 CRITICAL（嚴重）、WARNING（警告）或 INFO（一般）。
"""
        return prompt

    def _call_gemini_api(self, prompt: str) -> Optional[str]:
        """Invokes Google Gemini API if API key is configured."""
        if not self.api_key:
            return None

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model_name}:generateContent?key={self.api_key}"
        headers = {"Content-Type": "application/json"}
        payload = {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": 0.2, "maxOutputTokens": 1000},
        }

        try:
            req = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers=headers)
            with urllib.request.urlopen(req, timeout=15) as resp:
                result = json.loads(resp.read().decode("utf-8"))
                candidates = result.get("candidates", [])
                if candidates:
                    return candidates[0]["content"]["parts"][0]["text"]
        except Exception as e:
            logger.warning(f"Gemini API call failed ({e}); switching to expert fallback engine.")

        return None

    def _expert_rule_diagnosis(self, events: List[Dict[str, Any]]) -> DiagnosticReport:
        """
        Deterministic expert system providing structured diagnosis when API key is unavailable.
        Ensures 100% offline autonomy and reproducibility.
        """
        if not events:
            return DiagnosticReport(
                incident_title="系統運作常態報告",
                severity="INFO",
                incident_duration_s=0.0,
                probable_cause="5G URLLC 鏈路正常，無通訊降階事件。",
                impact_assessment="號誌維持 Level 0 全局協同控制，路口通行良好。",
                operator_recommendations=["持續監測 5G 切片 QoS 指標。"],
                raw_response="無異常事件記錄。",
                llm_source="Domain-Expert-Fallback",
            )

        # Analyze events
        l2_events = [e for e in events if e.get("to_level") == 2 or e.get("from_level") == 2]
        total_duration = 0.0
        if len(events) >= 2:
            total_duration = events[-1].get("timestamp_s", 0) - events[0].get("timestamp_s", 0)

        is_fiber_cut = any("fiber cut" in str(e.get("reason", "")).lower() or e.get("packet_loss_rate", 0) >= 0.9 for e in events)
        max_queued = max([e.get("total_queued", 0) for e in events] or [0])

        if is_fiber_cut:
            cause = "回程光纖實體中斷或 5G MEC 邊緣基站硬體離線（持續超過 30 秒，封包遺失率達到 100%）。"
            severity = "CRITICAL"
        else:
            cause = "5G 無線通道訊號劣化或大型集會尖峰頻寬排擠（延遲劇增，抖動異常）。"
            severity = "WARNING"

        impact = (
            f"通訊故障持續約 {total_duration:.1f} 秒。在此期間 ResiLight 即時觸發 Level 2 Max Pressure "
            f"本地規則引擎，路口排隊壓制在 {max_queued} 輛以內，未發生連鎖溢流或癱瘓；"
            f"連線恢復後無擾動機制使時制平滑銜接。"
        )

        recommendations = [
            "派員排查該路口路側光化箱與 5G 路由器回程光纖纜線是否遭道路施工挖損。",
            "通知中華電信行動網路維運中心（NOC），確認該基站扇區是否啟動專屬網路切片（Slicing）保護。",
            "維持目前 Max Pressure 審計日誌歸檔，供後續交通工程與通訊 SLA 履約驗證。",
        ]

        raw = f"""### 【ResiLight 智慧號誌維運中心診斷報告】
- **事件標題**：5G 鏈路嚴重劣化暨 Level 2 後備防護觸發
- **嚴重程度**：{severity}
- **故障歷時**：約 {total_duration:.1f} 秒
- **成因推論**：{cause}
- **交通衝擊**：{impact}
- **處置建議**：
  1. {recommendations[0]}
  2. {recommendations[1]}
  3. {recommendations[2]}
"""
        return DiagnosticReport(
            incident_title="5G 鏈路中斷暨 Level 2 後備防護事件",
            severity=severity,
            incident_duration_s=total_duration,
            probable_cause=cause,
            impact_assessment=impact,
            operator_recommendations=recommendations,
            raw_response=raw,
            llm_source="Domain-Expert-Fallback",
        )

    def diagnose(self, log_filepath: str) -> DiagnosticReport:
        """
        Executes end-to-end diagnosis of an event log.
        """
        events = self.load_events(log_filepath)
        prompt = self.generate_prompt(events)

        api_response = self._call_gemini_api(prompt)
        if api_response:
            return DiagnosticReport(
                incident_title="5G 鏈路通訊劣化診斷（Gemini AI 生成）",
                severity="CRITICAL" if "CRITICAL" in api_response else "WARNING",
                incident_duration_s=events[-1].get("timestamp_s", 0) - events[0].get("timestamp_s", 0) if len(events) >= 2 else 0.0,
                probable_cause="詳見 AI 分析文字",
                impact_assessment="詳見 AI 分析文字",
                operator_recommendations=["請參照 AI 生成之維運處置建議。"],
                raw_response=api_response,
                llm_source="Gemini-API",
            )

        # Fallback to expert diagnostic rule engine
        return self._expert_rule_diagnosis(events)
